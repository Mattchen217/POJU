            function applyBuiltCopy(locale) {
              const pack = BUILT_COPY[locale] || BUILT_COPY.en;
              if (!pack) return;
              document.querySelectorAll('[data-built]').forEach((el) => {
                const key = el.getAttribute('data-built');
                if (!key || typeof pack[key] !== 'string') return;
                if (key === 'heading') el.innerHTML = pack[key];
                else el.textContent = pack[key];
              });
            }

