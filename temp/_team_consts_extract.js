            function applyEngineCopy(locale) {
              const pack = ENGINE_COPY[locale] || ENGINE_COPY.en;
              document.querySelectorAll('[data-engine]').forEach((card) => {
                const key = card.getAttribute('data-engine');
                const copy = pack[key];
                if (!copy) return;
                const title = card.querySelector('[data-engine-title]');
                const subtitle = card.querySelector('[data-engine-subtitle]');
                const tagline = card.querySelector('[data-engine-tagline]');
                const desc = card.querySelector('[data-engine-desc]');
                const cta = card.querySelector('[data-engine-cta]');
                if (title) title.textContent = copy.title;
                if (tagline) tagline.textContent = copy.tagline;
                if (desc) desc.textContent = copy.description;
                if (cta) cta.textContent = copy.cta;
              });
            }
            